const I18nContext = createContext()

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && translations[saved]) return saved
    // Auto-detect from browser
    const browserLang = navigator.language?.split('-')[0]
    if (browserLang === 'pt') return 'pt'
    if (browserLang === 'en') return 'en'
    return 'es'
  })

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang)
    document.documentElement.lang = lang
  }, [lang])

  const t = (key, params = {}) => {
    let str = translations[lang]?.[key] || translations.es[key] || key
    // Replace {n}, {name}, etc.
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v)
    })
    return str
  }

  const toggleLang = () => setLang(prev => {
    if (prev === 'es') return 'en'
    if (prev === 'en') return 'pt'
    return 'es'
  })

  return (
    <I18nContext.Provider value={{ lang, setLang, t, toggleLang }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

// Standalone lang getter for use outside React (e.g., Zustand stores)
export function getLang() {
  return localStorage.getItem('padelzero_lang') || 'es'
}

export function tStandalone(key, params = {}) {
  const lang = getLang()
  let str = translations[lang]?.[key] || translations.es[key] || key
  Object.entries(params).forEach(([k, v]) => {
    str = str.replace(`{${k}}`, v)
  })
  return str
}
